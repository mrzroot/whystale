def test_protobuf_fresh_and_gitignored_outputs(tmp_path):
    mk(tmp_path, ".gitignore", "gen/\n", ago(9000))
    mk(tmp_path, "a.proto", "x", ago(1000))
    mk(tmp_path, "gen/a_pb2.py", "#", ago(100))
    assert scan(tmp_path, only={"generated"}).findings == []
